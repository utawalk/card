// ============================================================
//  cards.js — カード共通データ（パワー）
//  各カード（スート × ランク、52枚）に設定された「パワー」の値。
//  ゲーム内の得点計算など、全ゲーム共通で参照する一元データ。
//
//  今後、スートやランクごとにパワーの数値を調整したくなったら、
//  このファイルの数値だけを書き換えれば全ゲームに反映される。
